"""Key TS 38.521-1 tables transcribed from ts_13852101v180500p.pdf.

Primary values are V18.5.0. Where V17.5.0 differed, the old value is
kept as an "R17:" note — not as a second live table. Merged cells are
flattened so each band/BW still has a readable number. Blank = not specified.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class SpecTable:
    tid: str
    title: str
    page: int
    headers: tuple[str, ...]
    rows: tuple[tuple[str, ...], ...]
    notes: tuple[str, ...] = field(default_factory=tuple)


def _t(
    tid: str,
    title: str,
    page: int,
    headers: list[str],
    rows: list[list[str]],
    notes: list[str] | None = None,
) -> SpecTable:
    return SpecTable(
        tid,
        title,
        page,
        tuple(headers),
        tuple(tuple(r) for r in rows),
        tuple(notes or ()),
    )


